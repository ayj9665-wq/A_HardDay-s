/**
 * `crypto.randomUUID` only exists in a secure context, and the desktop webview
 * is served from a custom scheme that is not guaranteed to be one. Falling back
 * to `getRandomValues`, which has no such requirement, keeps task creation from
 * throwing on the platforms where it is missing.
 */
export function createId(): string {
  if (typeof crypto.randomUUID === "function") return crypto.randomUUID();

  const bytes = crypto.getRandomValues(new Uint8Array(16));
  bytes[6] = (bytes[6] & 0x0f) | 0x40; // version 4
  bytes[8] = (bytes[8] & 0x3f) | 0x80; // variant 1
  const hex = [...bytes].map((byte) => byte.toString(16).padStart(2, "0")).join("");
  return [
    hex.slice(0, 8),
    hex.slice(8, 12),
    hex.slice(12, 16),
    hex.slice(16, 20),
    hex.slice(20),
  ].join("-");
}
